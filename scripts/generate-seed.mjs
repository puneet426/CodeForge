// Builds supabase/seed.sql from the alumni list in src/data/alumni.js.
// Run: node scripts/generate-seed.mjs
import { writeFileSync } from 'node:fs';
import { alumni } from '../src/data/alumni.js';

const q = (v) => `'${String(v ?? '').replace(/'/g, "''")}'`;

const rows = alumni.map((a, i) =>
  `  (${q(a.name)}, ${q(a.role)}, ${q(a.company)}, ${q(a.sector)}, ${q(a.linkedin)}, ${q(a.group === 'leaders' ? 'leaders' : 'tech')}, ${i})`);

const sql = `-- Generated by scripts/generate-seed.mjs from src/data/alumni.js — do not edit by hand.
-- Run once in Supabase → SQL Editor after schema.sql. Re-running is safe:
-- rows whose LinkedIn URL already exists are skipped.

insert into public.alumni (name, role, company, sector, linkedin, category, sort_order) values
${rows.join(',\n')}
on conflict (linkedin) do nothing;
`;

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Wrote ${alumni.length} alumni to supabase/seed.sql`);
