// Builds supabase/seed.sql from the bundled data:
//   src/data/alumni.js  → public.alumni
//   src/data/events.js  → public.events
// Run: node scripts/generate-seed.mjs
import { writeFileSync } from 'node:fs';
import { alumni } from '../src/data/alumni.js';
import { events } from '../src/data/events.js';

const q = (v) => (v === undefined || v === null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a && a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const json = (v) => `${q(JSON.stringify(v || []))}::jsonb`;
const bool = (v) => (v ? 'true' : 'false');

const alumniRows = alumni.map((a, i) =>
  `  (${q(a.name)}, ${q(a.role) === 'null' ? "''" : q(a.role)}, ${q(a.company) === 'null' ? "''" : q(a.company)}, ${q(a.sector) === 'null' ? "''" : q(a.sector)}, ${q(a.linkedin)}, '${a.group === 'leaders' ? 'leaders' : 'tech'}', ${i})`);

const eventRows = events.map((e) =>
  `  (${[
    q(e.slug), q(e.title), q(e.tagline), q(e.category), q(e.start), q(e.end),
    q(e.dateLabel), q(e.time), q(e.venue), q(e.collab), q(e.banner), q(e.trailer),
    bool(e.featured), bool(e.registration), q(e.description), arr(e.highlights),
    json(e.sessions), arr(e.gallery), q(e.galleryTitle),
  ].join(', ')})`);

const sql = `-- Generated by scripts/generate-seed.mjs — do not edit by hand.
-- Run in Supabase → SQL Editor after schema.sql. Re-running is safe:
-- rows that already exist (same LinkedIn URL / event slug) are skipped.

-- ${alumni.length} alumni
insert into public.alumni (name, role, company, sector, linkedin, category, sort_order) values
${alumniRows.join(',\n')}
on conflict (linkedin) do nothing;

-- ${events.length} events
insert into public.events (slug, title, tagline, category, start_at, end_at, date_label, time_label, venue, collab, banner, trailer, featured, registration, description, highlights, sessions, gallery, gallery_title) values
${eventRows.join(',\n')}
on conflict (slug) do nothing;
`;

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Wrote ${alumni.length} alumni and ${events.length} events to supabase/seed.sql`);
